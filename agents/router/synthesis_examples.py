def _tokenize(text: str) -> set:
    import re
    return set(re.findall(r'[가-힣A-Za-z0-9]+', (text or '').lower()))


def select_examples(query: str, k: int = 1) -> list:
    """질문과 태그 겹침이 가장 큰 예시 k개를 반환 (없으면 첫 k개)."""
    q_tokens = _tokenize(query)
    scored = []
    for ex in EXAMPLES:
        score = sum(1 for tag in ex["tags"] if tag.lower() in q_tokens or any(tag.lower() in t for t in q_tokens))
        scored.append((score, ex))
    scored.sort(key=lambda x: x[0], reverse=True)
    top = [ex for score, ex in scored if score > 0][:k]
    if not top:
        top = EXAMPLES[:k]
    return top
