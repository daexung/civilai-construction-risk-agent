def add(page, number, kind, title, bbox, rows, features=()):
    """Rows contain (identifiers, (column hint, printed value), ...)."""
    facts = [[list(labels), [[hint, value] for hint, value in values]]
             for labels, *values in rows]
    TABLES.append(dict(id=f"v2_{page}_t{number}", page=page, kind=kind,
                       title=title, bbox_pt=bbox, features=list(features), facts=facts))


def single(page, number, kind, title, bbox, hint, pairs, features=()):
    add(page, number, kind, title, bbox,
        [([str(label)], (hint, str(value))) for label, value in pairs], features)


