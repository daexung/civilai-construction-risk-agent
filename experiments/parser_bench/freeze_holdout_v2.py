def review_html(tables):
    cards = []
    for t in tables:
        if t["kind"] != "targeted":
            continue
        rows = []
        for labels, values in t["facts"]:
            cells = "".join(f"<li><b>{html.escape(hint or '값')}</b>: {html.escape(value)}</li>"
                            for hint, value in values)
            rows.append(f"<tr><th>{html.escape(' / '.join(labels))}</th><td><ul>{cells}</ul></td></tr>")
        cards.append(f"""<section><h2>{html.escape(t['title'])} (PDF {t['page']}쪽)</h2>
          <div class="pair"><figure><img src="../experiments/parser_bench/results/holdout_v2/crops/{t['id']}.png" alt="원문 {t['id']}"><figcaption>원문 표 조각</figcaption></figure>
          <div><table><thead><tr><th>행 식별</th><th>원문에서 옮긴 값</th></tr></thead><tbody>{''.join(rows)}</tbody></table></div></div></section>""")
