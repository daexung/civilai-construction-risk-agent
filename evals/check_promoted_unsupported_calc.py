def check_conditional_cost_rate() -> None:
    """공구손료 요율이 정밀절단 여부(5%/2%)에 따라 다른 규칙 하나만 적용되는지 확인한다."""
    from decimal import Decimal, ROUND_DOWN
    from backend.agent.tools.calc.price import price_unit, select_rate_version
    package = spec("유지관리/2-1-30")["draft"]
    for precision, rate in ((True, Decimal("0.05")), (False, Decimal("0.02"))):
        inputs = {"volume": "300", "type": "B-Type", "tactile_block": False, "precision_cut": precision}
        units = adjusted_daily_crew(package, inputs)["unit_lines"]
