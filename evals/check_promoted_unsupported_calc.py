_READER = None
_PAGES: dict[int, str] = {}


def page_text(index: int | tuple) -> str:
    if isinstance(index, tuple):
        return "".join(page_text(item) for item in index)
    global _READER
    if index not in _PAGES:
        if _READER is None:
            from pypdf import PdfReader  # PDF 대조가 필요할 때만 불러온다
            _READER = PdfReader(PDF)
        _PAGES[index] = re.sub(r"\s+", "", _READER.pages[index].extract_text() or "")
    return _PAGES[index]


def spec(key: str) -> dict:
    division, section = key.split("/")
    return json.loads((ROOT / f"data/drafts/specs/{division}/{section}.json").read_text(encoding="utf-8"))


