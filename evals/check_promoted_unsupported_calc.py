def check_unit_denominator_repairs() -> None:
    """표 단위에 보충한 분모(예: 인/㎥)가 모두 그 표 청크의 원문 표머리 `basis`('(㎥당)')에서 왔는지 확인한다."""
    report = json.loads((ROOT / "evals/runtime_validation/table-unit-denominator-2026-10-19.json").read_text(encoding="utf-8"))
    chunks = {}
    for line in (ROOT / "data/processed/chunks.all.jsonl").read_text(encoding="utf-8").splitlines():
        if line.strip():
            chunk = json.loads(line)
            chunks[chunk["chunk_id"]] = chunk
    for item in report["changed"]:
        assert item["origin"] == "chunk.basis", item
        basis = "".join(chunks[item["table"]]["basis"].split())
        denominator = item["after"].split(",")[0].split("/", 1)[1].replace("1km", "km")
        assert denominator.replace("1km", "km") in basis.replace("측선", "").replace("1km", "km"), (item, basis)
        package = json.loads((ROOT / item["path"]).read_text(encoding="utf-8"))
        table = next(t for t in package["draft"]["tables"] if t["id"] == item["table"])
        assert table["unit"] == item["after"], item
    print(f"ok 표 단위 분모 보충 {len(report['changed'])}건: 모두 원문 표머리 basis와 일치")


